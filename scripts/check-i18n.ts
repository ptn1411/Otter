/**
 * i18n gate for the extension (Chrome _locales standard).
 * Checks, without a browser:
 *  1. vi/en _locales parity (same keys, non-empty, same {placeholder} sets).
 *  2. messages.ts is up to date with _locales (regenerate and compare).
 *  3. Every t("...") key used in extension/src exists in _locales.
 *  4. Every data-i18n key in extension HTML exists in _locales.
 * Exit non-zero on any failure. Run: bun scripts/check-i18n.ts
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { execSync } from "node:child_process";

const root = path.resolve(import.meta.dir, "..");
const errors: string[] = [];

function placeholders(message: string): string[] {
  return [...new Set([...message.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((m) => m[1]))].sort();
}

function readLocale(lang: string): Record<string, string> {
  const raw = JSON.parse(fs.readFileSync(path.join(root, "extension", "_locales", lang, "messages.json"), "utf8"));
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(raw as Record<string, { message: string }>)) out[k] = v.message;
  return out;
}

const vi = readLocale("vi");
const en = readLocale("en");
const viKeys = Object.keys(vi).sort();
const enKeys = Object.keys(en).sort();
if (JSON.stringify(viKeys) !== JSON.stringify(enKeys)) {
  errors.push(`parity: only vi=${viKeys.filter((k) => !enKeys.includes(k)).join(",")} only en=${enKeys.filter((k) => !viKeys.includes(k)).join(",")}`);
}
for (const k of viKeys) {
  if (!vi[k]?.trim() || !en[k]?.trim()) errors.push(`empty: ${k}`);
  if (JSON.stringify(placeholders(vi[k])) !== JSON.stringify(placeholders(en[k]))) errors.push(`placeholder mismatch: ${k}`);
}

// messages.ts freshness: regenerate to a temp copy and compare key sets
const before = fs.readFileSync(path.join(root, "extension", "src", "i18n", "messages.ts"), "utf8");
execSync("bun scripts/generate-i18n.ts", { cwd: root, stdio: "pipe" });
const after = fs.readFileSync(path.join(root, "extension", "src", "i18n", "messages.ts"), "utf8");
if (before !== after) errors.push("messages.ts is stale — regenerated by this check; re-run tests and commit the regenerated file");

// t("...") keys in extension/src
function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(p));
    else if (entry.name.endsWith(".ts")) out.push(p);
  }
  return out;
}
const used = new Set<string>();
for (const file of walk(path.join(root, "extension", "src"))) {
  const text = fs.readFileSync(file, "utf8");
  // Word-boundary t(): "createElement(" must not match — require t() not preceded by a letter/digit/underscore.
  for (const m of text.matchAll(/(?:^|[^A-Za-z0-9_])t\(\s*"([A-Za-z0-9_.\-]+)"/g)) used.add(m[1]);
}
for (const k of [...used].sort()) {
  if (!(k in vi)) errors.push(`t() key not in _locales: ${k}`);
}

// data-i18n keys in extension HTML (options.html, sidepanel.html)
for (const html of ["options.html", "sidepanel.html"]) {
  const text = fs.readFileSync(path.join(root, "extension", html), "utf8");
  for (const m of text.matchAll(/data-i18n="([^"]+)"/g)) {
    if (!(m[1] in vi)) errors.push(`data-i18n key not in _locales (${html}): ${m[1]}`);
  }
}

if (errors.length) {
  console.error(`[-] check-i18n FAILED (${errors.length}):`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
console.log(`[+] check-i18n OK: ${viKeys.length} keys, ${used.size} t() keys used, HTML keys OK`);
